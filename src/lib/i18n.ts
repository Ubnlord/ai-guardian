const DICT: Record<Locale, Record<CopyKey, string>> = { en: EN, fr: FR, es: ES, pt: PT, ar: AR };

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "en" || value === "fr" || value === "es" || value === "pt" || value === "ar";
}

export function translate(locale: Locale, key: CopyKey): string {
  return DICT[locale][key] || EN[key];
}
